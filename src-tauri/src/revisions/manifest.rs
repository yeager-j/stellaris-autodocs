    #[test]
    fn pinned_identity_vectors() {
        // Pinned golden vectors, derived independently of this implementation by a Python
        // script written from the framing diagram above `derive_identity` alone:
        //
        //   SHA-256( "stellaris-docs/revision-id/v1" || 0x00
        //            || 0x05 || u64be(6)
        //            || 0x03 || u64be(schema)
        //            || 0x02 || u64be(64) || installation hex
        //            || 0x06 || u64be(2)
        //            ||   0x02 || u64be(10) || "target_mod"
        //            ||   0x02 || u64be(64) || target-mod fingerprint hex
        //            ||   0x02 || u64be(15) || "vanilla_content"
        //            ||   0x02 || u64be(64) || vanilla-content fingerprint hex
        //            || 0x01 || u64be(32) || analysis version vector digest
        //            || 0x04 || 0x01
        //            || 0x06 || u64be(entries)
        //            ||   0x02 || u64be(len) || logical path
        //            ||   0x02 || u64be(64)  || entry content hash hex )
        //
        // The nested digest is `analysis`'s own, which the script re-implements from
        // analysis/version.rs's framing and cross-checks against that module's independent
        // `pinned_current_digest` before deriving anything here.
        //
        // Change protocol: this is durable revision identity — the bundle's final path,
        // the state publication reference, and garbage collection's live set are all keyed
        // by it. A change to this framing, to the digest, or to what participates is a NEW
        // domain version (/v2) plus a BUNDLE_SCHEMA_VERSION bump, never a re-pin in place,
        // which would silently redefine every published revision's identity. Nothing has
        // been published yet, so no migration accompanies a bump today; that stops being
        // true the moment Task 6's protocol ships.
        assert_eq!(
            identity_of(&pinned_body()).to_hex(),
            "a386ac046fdd18dba6b6caae42a6ac8abc92d2621ad9dd9df55f5c0260894b19"
        );

        // A revision that carries no entries and documents an incomplete analysis is an
        // identity, not an absence — the same rule the empty source fingerprint follows.
        let mut empty = pinned_body();
        empty.documentation_is_complete = false;
        empty.required_entries = BTreeMap::new();
        assert_eq!(
            identity_of(&empty).to_hex(),
            "9c8f6826aed16d9913e888802828fcae6b9b804d4b249c66e280cdbff016131e"
        );
    }

    #[test]
    fn every_identity_component_changes_the_identifier() {
        // The claim the whole module rests on: two builds that differ in anything identity
        // covers must not share an identifier. A component silently dropped from the body
        // is invisible in every other test — this table is what observes it.
        type Mutate = fn(&mut Body);
        let base = identity_of(&pinned_body());
        let mutations: [(&str, Mutate); 7] = [
            ("bundle schema version", |b| b.schema += 1),
            ("mod installation", |b| {
                b.installation = ModInstallationId::derive(
                    DiscoveryLocationId::parse("00000000000000000000000000000001").unwrap(),
                    &path("ugc_2"),
                )
            }),
            ("target mod fingerprint", |b| {
                b.inputs.target_mod = SourceFingerprint::parse(PINNED_VANILLA).unwrap()
            }),
            ("vanilla content fingerprint", |b| {
                b.inputs.vanilla_content = SourceFingerprint::parse(PINNED_TARGET_MOD).unwrap()
            }),
            ("analysis version vector", |b| {
                b.analysis_versions.parsed_model += 1
            }),
            ("completeness", |b| {
                b.documentation_is_complete = !b.documentation_is_complete
            }),
            ("required entries", |b| {
                b.required_entries
                    .insert(path("documents/extra.json"), ContentHash::of(b"extra\n"));
            }),
        ];
        for (component, mutate) in mutations {
            let mut mutated = pinned_body();
            mutate(&mut mutated);
            assert_ne!(base, identity_of(&mutated), "component {component}");
        }

        // Swapping the two inputs is a different revision, not the same one relabelled:
        // documentation of mod A against build B is not documentation of B against A.
        let mut swapped = pinned_body();
        std::mem::swap(
            &mut swapped.inputs.target_mod,
            &mut swapped.inputs.vanilla_content,
        );
        assert_ne!(base, identity_of(&swapped));

        // An entry's content, not merely its presence: a rebuilt document with the same
        // bundle path and different bytes is a different revision.
        let mut edited = pinned_body();
        edited.required_entries.insert(
            path("documents/entry-list.json"),
            ContentHash::of(b"{\"entries\":[{}]}\n"),
        );
        assert_ne!(base, identity_of(&edited));
    }

