    fn the_version_vector_enters_as_one_nested_digest() {
        // Pins the decision, not the value: `analysis` owns which components exist, and a
        // field-by-field re-encoding here would make `revisions` a second authority over
        // that list. The failure mode is silent — a component added in a later phase would
        // never reach this body — so the choice needs a test that a "simplification" to
        // flat fields cannot survive.
        let body = pinned_body();
        let actual = identity_of(&body);

        let mut nested = CanonicalDigest::new(REVISION_ID_DOMAIN);
        nested
            .begin_seq(6)
            .u64(body.schema.into())
            .text(&body.installation.to_string())
            .begin_map(2)
            .text("target_mod")
            .text(&body.inputs.target_mod.to_hex())
            .text("vanilla_content")
            .text(&body.inputs.vanilla_content.to_hex())
            .bytes(&body.analysis_versions.digest().0)
            .bool(body.documentation_is_complete)
            .begin_map(body.required_entries.len());
        for (logical, content) in &body.required_entries {
            nested.text(logical.as_str()).text(&content.to_hex());
        }
        assert_eq!(actual.to_hex(), nested.finish().to_hex());

        // The same body with the vector spelled out component by component — what a
        // reviewer might propose as "simpler". It must not produce this identifier.
        let mut flattened = CanonicalDigest::new(REVISION_ID_DOMAIN);
        flattened
            .begin_seq(6)
            .u64(body.schema.into())
            .text(&body.installation.to_string())
            .begin_map(2)
            .text("target_mod")
            .text(&body.inputs.target_mod.to_hex())
            .text("vanilla_content")
            .text(&body.inputs.vanilla_content.to_hex())
            .u64(body.analysis_versions.source_enumeration.into())
            .u64(body.analysis_versions.parsed_model.into())
            .u64(body.analysis_versions.resolution_profile.into())
            .u64(body.analysis_versions.documentation.into())
            .u64(body.analysis_versions.localization_interpretation.into())
            .u64(body.analysis_versions.search.into())
            .u64(body.analysis_versions.canonical_encoding.into())
            .u64(body.analysis_versions.hidden_route_identity.into())
            .u64(body.analysis_versions.analysis_issue_propagation.into())
            .bool(body.documentation_is_complete)
            .begin_map(body.required_entries.len());
        for (logical, content) in &body.required_entries {
            flattened.text(logical.as_str()).text(&content.to_hex());
        }
        assert_ne!(actual.to_hex(), flattened.finish().to_hex());

        // And the consequence nesting buys: a component `revisions` never names — an asset
        // recipe, which Phase 8 registers — moves the identifier with no change here.
        let mut later_phase = pinned_body();
        later_phase
            .analysis_versions
            .asset_recipes
            .insert("svg-to-png".to_owned(), 1);
        assert_ne!(actual, identity_of(&later_phase));
    }

    #[test]
    fn a_sealed_manifest_recomputes_its_own_identifier() {
        // `seal` and `recomputed_identity` route through one derivation; if they could
        // drift, every freshly published bundle would fail its own validation and the
        // failure would look exactly like tampering.
        let body = pinned_body();
        let manifest = BundleManifest::seal(&candidate(&body), body.required_entries.clone());
        assert_eq!(manifest.identifier(), manifest.recomputed_identity());
        assert_eq!(manifest.identifier(), identity_of(&body));
        assert_eq!(manifest.schema(), BUNDLE_SCHEMA_VERSION);

        // Sealing is a function of the candidate and the entries, not of when it ran.
        assert_eq!(
            BundleManifest::seal(&candidate(&body), body.required_entries.clone()),
            manifest
        );

        // The accessors report what seal was given, so a validator comparing a stored
        // manifest against a fresh observation reads the same facts identity was built on.
        assert_eq!(manifest.installation(), body.installation);
        assert_eq!(manifest.inputs(), &body.inputs);
        assert_eq!(manifest.analysis_versions(), &body.analysis_versions);
        assert!(manifest.documentation_is_complete());
        assert_eq!(manifest.required_entries(), &body.required_entries);
    }

    #[test]
    fn a_tampered_entry_hash_is_parsed_and_then_refused_by_recomputation() {
        // The attack the identifier exists to stop: swap a document in a published bundle
        // and rewrite the manifest's hash for it so the bundle still validates entry by
        // entry. `parse` accepts the document — reading is not judging — and recomputation
        // is what refuses it.
        let body = pinned_body();
        let sealed = BundleManifest::seal(&candidate(&body), body.required_entries.clone());
        let tampered_json = serde_json::to_string(&sealed).unwrap().replace(
            &ContentHash::of(b"{\"entries\":[]}\n").to_hex(),
            &ContentHash::of(b"{\"entries\":[{\"evil\":true}]}\n").to_hex(),
        );

        let tampered = BundleManifest::parse(tampered_json.as_bytes()).unwrap();
        assert_eq!(tampered.identifier(), sealed.identifier());
        assert_ne!(tampered.recomputed_identity(), tampered.identifier());

        // The same refusal for a manifest whose printed analysis vector disagrees with the
        // identifier it claims: recomputation digests the *parsed* vector, so the
        // human-readable rendering cannot drift away from what identity bound.
        let restated = serde_json::to_string(&sealed)
            .unwrap()
            .replace("\"parsed_model\":1", "\"parsed_model\":2");
        let restated = BundleManifest::parse(restated.as_bytes()).unwrap();
        assert_ne!(restated.recomputed_identity(), restated.identifier());
    }

    #[test]
    fn a_rebound_discovery_location_does_not_change_the_identifier() {
        // "A rebind must not change a revision id" (docs/technical-design.md, "Installation
        // identity"): a location's absolute path is editable configuration, so it enters
        // neither `ModInstallationId` nor this body — publication takes the location as a
        // separate argument and `seal` cannot be handed one.
        let location = DiscoveryLocationId::generate();
        let before = ModInstallationId::derive(location, &path("ugc_1"));
        let after_rebind = ModInstallationId::derive(location, &path("ugc_1"));
        let mut body = pinned_body();
        body.installation = before;
        let mut rebound = pinned_body();
        rebound.installation = after_rebind;
        assert_eq!(identity_of(&body), identity_of(&rebound));

        // The other half of the same rule, stated so it is not mistaken for a defect: a
        // *different* Discovery Location is a different Mod Installation, and therefore
        // legitimately a different revision.
        let mut elsewhere = pinned_body();
        elsewhere.installation =
            ModInstallationId::derive(DiscoveryLocationId::generate(), &path("ugc_1"));
        assert_ne!(identity_of(&body), identity_of(&elsewhere));
    }

    #[test]
    fn a_manifest_round_trips_with_every_optional_field_absent() {
        // Manifest validation hashes bytes without parsing them, so an intact but
        // undecodable manifest publishes and then fails its first read — the
        // revision-bundle spike's actual failure (docs/technical-design.md:651). A
        // revision with no required entries is the shape that reaches it: `required_entries`
        // is the manifest's only defaulted field, and a bundle written before any document
        // type exists omits it entirely.
        let minimal = BundleManifest::parse(
            format!(
                r#"{{"identifier":"{id}","schema":1,"installation":"{installation}",
                     "inputs":{{"target_mod":"{target}","vanilla_content":"{vanilla}"}},
                     "analysis_versions":{{"source_enumeration":3,"parsed_model":1,
                       "resolution_profile":1,"documentation":1,
                       "localization_interpretation":1,"search":1,"canonical_encoding":1,
                       "hidden_route_identity":1,"analysis_issue_propagation":1}},
                     "documentation_is_complete":false}}"#,
                // Independently derived alongside the other pinned vectors: the same body
                // with no asset recipes and no required entries.
                id = "242949eeccfc8ca9f2effe194e4a012257eb5e1659c215d84288235281b6608c",
                installation = PINNED_INSTALLATION,
                target = PINNED_TARGET_MOD,
                vanilla = PINNED_VANILLA,
            )
            .as_bytes(),
        )
        .unwrap();
        assert!(minimal.required_entries().is_empty());
        assert!(minimal.analysis_versions().asset_recipes.is_empty());

        // Nothing is skipped on write, so the value written back carries both absent
        // fields explicitly and reads as the same manifest.
        let encoded = serde_json::to_vec(&minimal).unwrap();
        assert_eq!(BundleManifest::parse(&encoded).unwrap(), minimal);

        // Round-tripping does not disturb identity: the decoded manifest still recomputes
        // to the identifier the document claimed.
        assert_eq!(minimal.recomputed_identity(), minimal.identifier());
    }

    #[test]
    fn a_pinned_schema_1_manifest_decodes_and_recomputes_its_identifier() {
        // The wire form is a contract with every bundle already on disk, so it is pinned
        // as text rather than regenerated from the types. This is also the tripwire
        // `BundleManifest::parse` names: a newly required field anywhere in the document —
        // including a tenth analysis component — makes this literal stop decoding, which
        // is precisely when BUNDLE_SCHEMA_VERSION must be bumped.
        let manifest = BundleManifest::parse(PINNED_MANIFEST_JSON.as_bytes()).unwrap();
        assert_eq!(manifest.recomputed_identity(), manifest.identifier());
        assert_eq!(
            manifest.identifier().to_hex(),
            "a386ac046fdd18dba6b6caae42a6ac8abc92d2621ad9dd9df55f5c0260894b19"
        );
        assert_eq!(manifest.required_entries().len(), 2);

        // The stored form is what a person reads, so a decomposed spelling of an entry
        // path normalizes to the same entry a fresh build would write rather than becoming
        // a second entry that no file satisfies.
        let decomposed = PINNED_MANIFEST_JSON.replace("t\\u00e9ch.json", "te\\u0301ch.json");
        assert_eq!(
            BundleManifest::parse(decomposed.as_bytes())
                .unwrap()
                .required_entries(),
            manifest.required_entries()
        );
    }

    #[test]
    fn a_stored_traversal_entry_path_fails_to_parse() {
        // A required entry is a path the validator will open. Refusing it while it is
        // still text means no stage ever resolves `../../etc/passwd` against a real
        // directory (canonical/path.rs's deserialize rationale); absolute paths and
        // backslashes are the same escape by another spelling.
        for hostile in [
            "../../etc/passwd",
            "documents/../../../etc/passwd",
            "/etc/passwd",
            "C:/Windows/System32/config/SAM",
        ] {
            let document = PINNED_MANIFEST_JSON.replace("documents/entry-list.json", hostile);
            let error = BundleManifest::parse(document.as_bytes()).unwrap_err();
            assert!(
                matches!(error, ManifestParseError::Malformed { .. }),
                "accepted {hostile}: {error:?}"
            );
            // The refusal names the offending value, so a rejected bundle is diagnosable
            // from the error alone rather than only from a position in the document.
            assert!(error.to_string().contains(hostile), "{error}");
        }
    }

    #[test]
    fn an_unsupported_schema_is_distinguished_from_a_damaged_manifest() {
        // The decision recorded on `BundleManifest::parse`: the schema version is read
        // first and is the only forward-compatibility signal. A bundle from another build
        // is rebuilt; a bundle claiming our schema and failing to decode is damaged. They
        // must not be reported as each other — a damaged manifest excused as "newer" is
        // one whose asset references garbage collection never enumerated.
        let newer = PINNED_MANIFEST_JSON.replace("\"schema\": 1", "\"schema\": 2");
        assert_eq!(
            BundleManifest::parse(newer.as_bytes()).unwrap_err(),
            ManifestParseError::UnsupportedSchema { found: 2 }
        );

        // A missing analysis component under *our* schema is damage, not a newer build.
        // Nine of the ten components are required on the read side, so a future build that
        // adds one owes a BUNDLE_SCHEMA_VERSION bump; without it this is the arm reached,
        // and refusing is the conservative answer.
        let gutted = PINNED_MANIFEST_JSON.replace("\"parsed_model\": 1,", "");
        assert!(matches!(
            BundleManifest::parse(gutted.as_bytes()).unwrap_err(),
            ManifestParseError::Malformed { .. }
        ));

        // Truncation, an absent schema field, and a non-manifest document are all damage.
        let truncated = &PINNED_MANIFEST_JSON[..PINNED_MANIFEST_JSON
            .find("\"analysis_versions\"")
            .expect("the pinned manifest names its analysis versions")];
        for damaged in [
            truncated,
            r#"{"identifier":"deadbeef"}"#,
            "{}",
            "not json at all",
        ] {
            assert!(
                matches!(
                    BundleManifest::parse(damaged.as_bytes()),
                    Err(ManifestParseError::Malformed { .. })
                ),
                "accepted {damaged}"
            );
        }

        // A newer manifest carrying an *extra* component decodes — nothing declares
        // `deny_unknown_fields` — and then fails closed at recomputation, because the
        // component it dropped is one identity bound.
        let extra = PINNED_MANIFEST_JSON.replace(
            "\"analysis_issue_propagation\": 1,",
            "\"analysis_issue_propagation\": 1, \"future_component\": 4,",
        );
        let decoded = BundleManifest::parse(extra.as_bytes()).unwrap();
        assert_eq!(decoded.recomputed_identity(), decoded.identifier());
    }

    #[test]
    fn identifiers_round_trip_through_their_rendered_form_and_through_state() {
        // The bundle's directory name and the state publication reference are both built
        // from this value, so it must survive rendering, storage, and being read back out
        // of a state document that never parsed it.
        let identity = identity_of(&pinned_body());
        let rendered = identity.to_hex();
        assert_eq!(rendered.len(), 64);
        assert_eq!(rendered, identity.to_string());
        assert_eq!(RevisionIdentity::parse(&rendered), Ok(identity));

        let stored: RevisionId = identity.into();
        assert_eq!(stored.0, rendered);
        assert_eq!(RevisionIdentity::try_from(&stored), Ok(identity));

        // `state` preserves whatever token it was handed, so the way back is fallible and
        // refuses before any path is built from the value.
        for hostile in [
            "",
            "abc",
            &rendered.to_uppercase(),
            &format!("{rendered}00"),
        ] {
            assert_eq!(
                RevisionIdentity::try_from(&RevisionId(hostile.to_owned())),
                Err(IdentityParseError)
            );
        }
        // A traversal spelled as a stored token is refused by the same rule, structurally
        // rather than by a path check bolted on later.
        assert_eq!(
            RevisionIdentity::try_from(&RevisionId("../../etc".to_owned())),
            Err(IdentityParseError)
        );

        // Serde is the rendered hex, strictly: one identity has one stored spelling.
        assert_eq!(
            serde_json::to_string(&identity).unwrap(),
            format!("\"{rendered}\"")
        );
        assert_eq!(
            serde_json::from_str::<RevisionIdentity>(&format!("\"{rendered}\"")).unwrap(),
            identity
        );
        assert!(
            serde_json::from_str::<RevisionIdentity>(&format!("\"{}\"", rendered.to_uppercase()))
                .is_err()
        );
        let error = serde_json::from_str::<RevisionIdentity>("\"not-an-id\"").unwrap_err();
        assert!(error.to_string().contains("not-an-id"), "{error}");
    }

    #[test]
    fn manifest_errors_display_and_implement_std_error() {
        // Task 4's validator and Task 6's protocol `?` and log these; both need Display,
        // and std::error::Error is what makes `?` conversion available (the same rationale
        // as state/mutations.rs:638).
        fn assert_error<E: std::error::Error>(error: &E) -> String {
            error.to_string()
        }
        assert!(!assert_error(&IdentityParseError).is_empty());
        assert!(assert_error(&IdentityParseError).contains("64 lowercase hex"));

        let unsupported = assert_error(&ManifestParseError::UnsupportedSchema { found: 7 });
        assert!(unsupported.contains('7'), "{unsupported}");
        assert!(unsupported.contains("rebuilt"), "{unsupported}");
        assert!(!unsupported.contains("UnsupportedSchema"), "{unsupported}");

        let malformed = assert_error(&ManifestParseError::Malformed {
            detail: "expected value at line 1 column 1".to_owned(),
        });
        assert!(malformed.contains("line 1 column 1"), "{malformed}");
        assert!(!malformed.contains("Malformed"), "{malformed}");
    }

