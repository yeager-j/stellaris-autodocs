/// The bundle's on-disk shape, not its content. Bumped whenever a manifest written by
/// this build could not be read by the previous one — which includes adding a component
/// to [`AnalysisVersionVector`], because its fields are required on the read side.
/// An incompatible schema invalidates the revision and causes a rebuild; published
/// bundles are never migrated in place (docs/technical-design.md, "Revision reader").
pub const BUNDLE_SCHEMA_VERSION: u32 = 1;

const REVISION_ID_DOMAIN: &str = "stellaris-docs/revision-id/v1";

/// The canonical identifier of one Documentation Revision.
///
/// A strong 32-byte type rather than a `String`, because the bundle's final directory
/// name is built from it: "the revision identifier and final path are generated by the
/// host rather than derived from untrusted mod names" only holds if "64 lowercase hex" is
/// structural. [`state::RevisionId`](crate::state::model::RevisionId) stays an opaque
/// round-trip token for `state`, which must preserve whatever it was handed without
/// re-deciding what a revision identifier is; the conversions below are the one place the
/// two representations meet.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct RevisionIdentity([u8; 32]);

impl RevisionIdentity {
    /// Reads back a rendered identifier. Strict: exactly 64 lowercase hex characters, so
    /// one stored form has one parse and one bundle path (`canonical::hex`'s rule).
    pub fn parse(text: &str) -> Result<Self, IdentityParseError> {
        hex::decode::<32>(text).map(Self).ok_or(IdentityParseError)
    }

    pub fn to_hex(&self) -> String {
        hex::encode(&self.0)
    }
}

impl fmt::Display for RevisionIdentity {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        hex::write(f, &self.0)
    }
}

/// A rendered identifier that is not exactly 64 lowercase hex characters.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct IdentityParseError;

impl fmt::Display for IdentityParseError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("invalid revision identifier: expected 64 lowercase hex characters")
    }
}

impl std::error::Error for IdentityParseError {}

/// Infallible outward: every identifier renders as the token `state` stores.
impl From<RevisionIdentity> for RevisionId {
    fn from(identity: RevisionIdentity) -> Self {
        RevisionId(identity.to_hex())
    }
}

/// Fallible inward: `state` preserves a token it never parsed, so a restored reference
/// may name anything a previous build or a hand edit left there. The refusal happens
/// before any path is built from it.
impl TryFrom<&RevisionId> for RevisionIdentity {
    type Error = IdentityParseError;

    fn try_from(stored: &RevisionId) -> Result<Self, Self::Error> {
        Self::parse(&stored.0)
    }
}

hex_string_serde!(RevisionIdentity, "expected 64 lowercase hex characters");

/// Everything a published bundle asserts about itself.
///
/// **Parse, don't validate — in two stages, and the second is not this module's.** Fields
/// are private and [`seal`](BundleManifest::seal) is the only in-process constructor, so a
/// manifest this process built is one whose `identifier` is the digest of its own body: it
/// cannot be assembled field by field into a state that lies. A manifest that arrived by
/// [`parse`](BundleManifest::parse) carries no such evidence — its `identifier` is whatever
/// the file said — and stays **untrusted** until validation calls
/// [`recomputed_identity`](BundleManifest::recomputed_identity) and finds it equal. That
/// check belongs to the bundle validator (Task 4) rather than to `parse`, because a
/// mismatch is one finding among missing entries and wrong entry hashes and is reported
/// with them, not as a decoding failure.
///
/// Accessors are read-only for the same reason: a mutable field would let a caller move a
/// manifest away from its identifier without going through a derivation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BundleManifest {
    identifier: RevisionIdentity,
    schema: u32,
    installation: ModInstallationId,
    inputs: RevisionInputs,
    /// Stored in full so a reader can name the component that invalidated a revision.
    /// Identity binds its `digest()`, not this rendering; a manifest whose printed vector
    /// disagrees with its identifier therefore fails validation rather than being believed.
    analysis_versions: AnalysisVersionVector,
    documentation_is_complete: bool,
    /// Bundle-relative logical path to the SHA-256 of that entry's bytes. A read-side
    /// default with nothing skipped on write, because manifest validation hashes bytes
    /// without parsing them and an intact-but-undecodable manifest publishes and then
    /// fails its first read (docs/technical-design.md:651).
    #[serde(default)]
    required_entries: BTreeMap<LogicalPath, ContentHash>,
}

impl BundleManifest {
    /// Builds the manifest for a staged bundle and seals it with its own identifier.
    ///
    /// `required_entries` maps each written bundle-relative path to the hash of the bytes
    /// written there; the candidate supplies everything else. Total by construction: there
    /// is no input a caller could supply that makes an identifier fail to derive.
    pub fn seal(
        candidate: &RevisionCandidate,
        required_entries: BTreeMap<LogicalPath, ContentHash>,
    ) -> Self {
        let identifier = derive_identity(
            BUNDLE_SCHEMA_VERSION,
            &candidate.installation,
            &candidate.inputs,
            &candidate.analysis_versions,
            candidate.documentation_is_complete,
            &required_entries,
        );
        Self {
            identifier,
            schema: BUNDLE_SCHEMA_VERSION,
            installation: candidate.installation,
            inputs: candidate.inputs.clone(),
            analysis_versions: candidate.analysis_versions.clone(),
            documentation_is_complete: candidate.documentation_is_complete,
            required_entries,
        }
    }

    /// Re-derives the identifier from this manifest's own body. Equal to
    /// [`identifier`](BundleManifest::identifier) is what makes a parsed manifest
    /// trustworthy; unequal means the file was edited, truncated, or written by something
    /// that is not this derivation.
    pub fn recomputed_identity(&self) -> RevisionIdentity {
        derive_identity(
            self.schema,
            &self.installation,
            &self.inputs,
            &self.analysis_versions,
            self.documentation_is_complete,
            &self.required_entries,
        )
    }

    /// Reads a stored manifest, deciding the schema question **before** anything else.
    ///
    /// The schema version is the only forward-compatibility signal a manifest carries, so
    /// it is read from a probe that ignores every other field. A version that is not ours
    /// is [`ManifestParseError::UnsupportedSchema`] — "written by a different build,
    /// rebuild" — and never reaches the typed decode, which would report the same bundle
    /// as damaged.
    ///
    /// **Decision: under our own schema version, an undecodable body is an invalid
    /// manifest, never "built under newer analysis".** The tempting alternative is to read
    /// a missing [`AnalysisVersionVector`] component as evidence of a newer build, since
    /// nine of its ten components are required on the read side. It is rejected because
    /// nothing distinguishes that shape from a truncated or hand-edited file, and guessing
    /// "newer" for a damaged manifest is the failure mode that matters: garbage collection
    /// derives its live set from manifests it can read, and a manifest excused as "newer"
    /// is one whose asset references were never enumerated. Adding a component to the
    /// vector is therefore a [`BUNDLE_SCHEMA_VERSION`] bump — it changes what an older
    /// reader can decode — and
    /// `a_pinned_schema_1_manifest_decodes_and_recomputes_its_identifier` is the tripwire
    /// that makes the omission visible.
    ///
    /// The mirror case fails closed on its own: a newer manifest carrying an *extra*
    /// component decodes here (nothing is `deny_unknown_fields`) but drops it, so its
    /// recomputed identity cannot match the stored one and validation refuses it.
    pub fn parse(bytes: &[u8]) -> Result<Self, ManifestParseError> {
        #[derive(Deserialize)]
        struct SchemaProbe {
            schema: u32,
        }

        let probe: SchemaProbe =
            serde_json::from_slice(bytes).map_err(|error| ManifestParseError::Malformed {
                detail: error.to_string(),
            })?;
        if probe.schema != BUNDLE_SCHEMA_VERSION {
            return Err(ManifestParseError::UnsupportedSchema {
                found: probe.schema,
            });
        }
        serde_json::from_slice(bytes).map_err(|error| ManifestParseError::Malformed {
            detail: error.to_string(),
        })
    }

    /// The identifier as stored. Trustworthy only after it has been compared with
    /// [`recomputed_identity`](BundleManifest::recomputed_identity).
    pub fn identifier(&self) -> RevisionIdentity {
        self.identifier
    }

    pub fn schema(&self) -> u32 {
        self.schema
    }

    pub fn installation(&self) -> ModInstallationId {
        self.installation
    }

    pub fn inputs(&self) -> &RevisionInputs {
        &self.inputs
    }

    pub fn analysis_versions(&self) -> &AnalysisVersionVector {
        &self.analysis_versions
    }

    pub fn documentation_is_complete(&self) -> bool {
        self.documentation_is_complete
    }

    pub fn required_entries(&self) -> &BTreeMap<LogicalPath, ContentHash> {
        &self.required_entries
    }
}

/// A stored manifest this build cannot interpret, separated by what the reader should do.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ManifestParseError {
    /// A different build's bundle shape. The revision is rebuilt, not repaired.
    UnsupportedSchema { found: u32 },
    /// Our schema version, and still not decodable: damaged, truncated, or hand-edited.
    Malformed { detail: String },
}

impl fmt::Display for ManifestParseError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnsupportedSchema { found } => write!(
                f,
                "bundle schema version {found} is not {BUNDLE_SCHEMA_VERSION}: \
                 this revision was written by a different build and must be rebuilt"
            ),
            Self::Malformed { detail } => write!(f, "manifest could not be read: {detail}"),
        }
    }
}

impl std::error::Error for ManifestParseError {}

/// The one derivation of a Revision identifier, private so that
/// [`BundleManifest::seal`] and [`BundleManifest::recomputed_identity`] cannot drift:
/// a writer and a validator that each encoded the body would eventually disagree, and the
/// disagreement would look exactly like tampering.
///
/// ```text
/// SHA-256( "stellaris-docs/revision-id/v1" || 0x00
///          || SEQ  || u64be(6)
///          || U64  || u64be(bundle schema version)
///          || TEXT || u64be(64) || mod installation id, lowercase hex
///          || MAP  || u64be(2)
///          ||   TEXT || u64be(10) || "target_mod"
///          ||   TEXT || u64be(64) || target-mod fingerprint, lowercase hex
///          ||   TEXT || u64be(15) || "vanilla_content"
///          ||   TEXT || u64be(64) || vanilla-content fingerprint, lowercase hex
///          || BYTES || u64be(32) || analysis version vector digest
///          || BOOL  || 0x01 when the documentation is complete, else 0x00
///          || MAP   || u64be(required entries)
///          ||   for each entry, ordered by logical-path bytes:
///          ||     TEXT || u64be(len) || bundle-relative logical path
///          ||     TEXT || u64be(64)  || SHA-256 of the entry's bytes, lowercase hex )
///
/// Tags: BYTES 0x01, TEXT 0x02, U64 0x03, BOOL 0x04, SEQ 0x05, MAP 0x06.
/// Every length is a big-endian u64; a TEXT length counts UTF-8 bytes, not characters.
/// ```
///
/// One rule decides TEXT against BYTES: **a value the manifest also stores as text enters
/// as exactly that text.** The installation identifier, both fingerprints, and every entry
/// hash are stored as rendered hex in this document, so the body hashes the document as
/// written and a value read out of the JSON needs no re-encoding to be checked. The
/// analysis version vector is the one item with no stored rendering — the manifest stores
/// the *vector*, not its digest — so it enters as the raw 32 bytes it is. Tag framing
/// keeps the two unconfusable regardless (`canonical::encode` separates TEXT from BYTES).
///
/// Item 1 is the bundle schema version; every *other* schema version this revision
/// depends on lives inside the analysis version vector, so items 1 and 4 together are the
/// design's "schema versions".
///
/// Item 2 is the installation identifier as text-of-hex rather than raw bytes, matching
/// [`ModInstallationId::derive`](crate::discovery::identity::ModInstallationId::derive),
/// which hashes a rendered `DiscoveryLocationId` for the same reason: the rendered form is
/// the established idiom here and avoids widening the type with a byte accessor nothing
/// else wants.
///
/// Item 3 names its two fingerprints instead of ordering them. Both are 64-hex strings, so
/// a positional pair would let a caller swap Target Mod for Vanilla Content and still
/// produce a well-formed body; named keys make the swap a different identifier. The two
/// keys are literals in canonical UTF-8 order (`target_mod` < `vanilla_content`), which is
/// what `begin_map` requires.
///
/// **Item 4 is the analysis version vector's own `digest()`, nested as 32 raw bytes, and
/// must stay that way.** `analysis` owns which components exist and how they are
/// canonically encoded, and carries the tests that prove it. Re-listing them here would
/// make `revisions` a second authority over that list, and the failure mode is silent: a
/// component added in a later phase would not reach this body, and two revisions built
/// from measurably different analysis behaviour would share one identifier. Nesting also
/// means a component bump changes every identifier with no framing change here.
/// `the_version_vector_enters_as_one_nested_digest` pins the choice.
///
/// Item 6 is a map rather than a sequence of pairs because `BTreeMap<LogicalPath, _>`
/// already orders by normalized UTF-8 bytes, which is exactly `begin_map`'s requirement —
/// canonical order for free, with no sort in this function to get wrong.
fn derive_identity(
    schema: u32,
    installation: &ModInstallationId,
    inputs: &RevisionInputs,
    analysis_versions: &AnalysisVersionVector,
    documentation_is_complete: bool,
    required_entries: &BTreeMap<LogicalPath, ContentHash>,
) -> RevisionIdentity {
    let mut digest = CanonicalDigest::new(REVISION_ID_DOMAIN);
    digest.begin_seq(6);

    digest.u64(schema.into());
    digest.text(&installation.to_string());

    digest
        .begin_map(2)
        .text("target_mod")
        .text(&inputs.target_mod.to_hex())
        .text("vanilla_content")
        .text(&inputs.vanilla_content.to_hex());

    digest.bytes(&analysis_versions.digest().0);
    digest.bool(documentation_is_complete);

    digest.begin_map(required_entries.len());
    for (logical, content) in required_entries {
        digest.text(logical.as_str()).text(&content.to_hex());
    }

    RevisionIdentity(digest.finish().0)
}

