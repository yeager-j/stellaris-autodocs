//! The Documentation Revision bundle manifest and the canonical Revision identifier
//! (docs/technical-design.md, "Revision bundles"; "Canonicalization and numeric
//! representation").
//!
//! One identifier names one build: "A Revision identifier is the SHA-256 digest of a
//! domain separator plus the canonical manifest body excluding the identifier itself."
//! Everything downstream — the bundle's final path, the state publication reference, the
//! freshness check, garbage collection's live set — is keyed by it, so this module owns
//! exactly one derivation and both the writer and the validator route through it.
//!
//! What is deliberately **excluded** from identity, each because it is configuration or
//! circumstance rather than the thing documented: the identifier itself, the Discovery
//! Location identifier (a rebind edits a location's path and must not invalidate a
//! revision), staging roots, final bundle paths, timestamps, and worker schedules.

